// per-color glyph cache
const cache = new Map<string, HTMLCanvasElement>();

function glyphCanvas(ch: string, color: string): HTMLCanvasElement | null {
  const key = ch + '|' + color;
  const hit = cache.get(key);
  if (hit) return hit;
  const rows = F[ch];
  if (!rows) return null;
  const cv = document.createElement('canvas');
  cv.width = GLYPH_W; cv.height = GLYPH_H;
  const g = cv.getContext('2d')!;
  g.fillStyle = color;
  for (let r = 0; r < GLYPH_H; r++) {
    const bits = rows[r];
    for (let c = 0; c < GLYPH_W; c++) {
      if (bits & (1 << (GLYPH_W - 1 - c))) g.fillRect(c, r, 1, 1);
    }
  }
  cache.set(key, cv);
  return cv;
}

/** Draw a single line of text. Returns pixel width. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string = PAL[0],
): number {
  let cx = x;
  for (const ch of text) {
    const g = glyphCanvas(ch, color);
    if (g) ctx.drawImage(g, cx, y);
    cx += ADVANCE;
  }
  return cx - x;
}

export function textWidth(text: string): number {
  return text.length * ADVANCE - 1;
}

/** Greedy word-wrap to a pixel width. */
export function wrapText(text: string, maxPx: number): string[] {
  const maxChars = Math.max(1, Math.floor((maxPx + 1) / ADVANCE));
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (test.length <= maxChars) line = test;
      else {
        if (line) out.push(line);
        // hard-split very long words
        let w = word;
        while (w.length > maxChars) {
          out.push(w.slice(0, maxChars));
          w = w.slice(maxChars);
        }
        line = w;
      }
    }
    out.push(line);
  }
  return out;
}

export function hasGlyph(ch: string): boolean {
  return !!F[ch];
}
